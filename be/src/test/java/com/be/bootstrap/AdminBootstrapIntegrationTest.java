package com.be.bootstrap;

import com.be.global.config.MemberSupportConfig;
import com.be.organization.repository.DepartmentRepository;
import com.be.security.JwtTestSupport;
import jakarta.validation.Validator;
import java.util.concurrent.*;
import org.junit.jupiter.api.*;
import org.junit.jupiter.api.extension.ExtendWith;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.NullAndEmptySource;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.boot.test.system.*;
import org.springframework.context.annotation.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.context.*;
import org.springframework.test.context.bean.override.mockito.MockitoSpyBean;
import org.springframework.transaction.annotation.*;
import org.springframework.validation.beanvalidation.LocalValidatorFactoryBean;
import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;

@DataJpaTest(showSql = false, properties = {"spring.jpa.hibernate.ddl-auto=none", "spring.sql.init.mode=never"})
@Import({AdminBootstrapService.class, MemberSupportConfig.class, AdminBootstrapIntegrationTest.Config.class})
@Transactional(propagation = Propagation.NOT_SUPPORTED)
@ExtendWith(OutputCaptureExtension.class)
class AdminBootstrapIntegrationTest {
    @TestConfiguration(proxyBeanMethods = false)
    static class Config {
        @Bean Validator validator() { return new LocalValidatorFactoryBean(); }
    }
    @Autowired AdminBootstrapService service;
    @Autowired JdbcTemplate jdbc;
    @Autowired PasswordEncoder encoder;
    @MockitoSpyBean DepartmentRepository departments;
    static final String PASSWORD = "bootstrap-fixture-password";
    AdminBootstrapProperties input() { return new AdminBootstrapProperties(true, "initial@example.test", PASSWORD, "Initial admin"); }
    void run(AdminBootstrapProperties input) { new AdminBootstrapRunner(service, input).run(null); }
    @DynamicPropertySource static void properties(DynamicPropertyRegistry r) {
        r.add("jwt.secret", JwtTestSupport::secret);
        r.add("jwt.access-token-ttl-seconds", () -> 300);
        r.add("jwt.refresh-token-ttl-seconds", () -> 3600);
    }
    @BeforeEach void schema() {
        // Disposable fixture only. Production schema stays exclusively in docs/LearnFlow.sql.
        jdbc.execute("CREATE TABLE departments(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code VARCHAR(50) UNIQUE NOT NULL,name VARCHAR(100) NOT NULL,parent_department_id BIGINT,is_active BOOLEAN NOT NULL,created_at TIMESTAMP,updated_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE job_positions(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code VARCHAR(50) UNIQUE NOT NULL,name VARCHAR(100) NOT NULL,is_active BOOLEAN NOT NULL,created_at TIMESTAMP,updated_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE members(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,employee_number VARCHAR(50) UNIQUE NOT NULL,email VARCHAR(255) UNIQUE NOT NULL,password_hash VARCHAR(255) NOT NULL,name VARCHAR(100) NOT NULL,department_id BIGINT NOT NULL REFERENCES departments(id),job_position_id BIGINT NOT NULL REFERENCES job_positions(id),status VARCHAR(20) NOT NULL,hire_date DATE NOT NULL,resigned_at TIMESTAMP,created_at TIMESTAMP,updated_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE member_roles(member_id BIGINT NOT NULL REFERENCES members(id),role VARCHAR(20) NOT NULL,PRIMARY KEY(member_id,role))");
    }
    @AfterEach void cleanup() { jdbc.execute("DROP ALL OBJECTS"); }
    long count(String table) { return jdbc.queryForObject("SELECT COUNT(*) FROM " + table, Long.class); }

    @Test void disabledDoesNotCreateOrRequireInputs() {
        assertThat(service.create(new AdminBootstrapProperties(false, null, null, null))).isFalse();
        assertThat(count("members")).isZero();
        assertThat(count("departments")).isZero();
    }
    @Test void createsActiveAdminOnlyWithEncodedPasswordAndRequiredOrganization(CapturedOutput output) {
        run(input());
        assertThat(count("members")).isOne();
        assertThat(jdbc.queryForList("SELECT role FROM member_roles", String.class)).containsExactly("ADMIN");
        assertThat(jdbc.queryForObject("SELECT status FROM members", String.class)).isEqualTo("ACTIVE");
        var hash = jdbc.queryForObject("SELECT password_hash FROM members", String.class);
        assertThat(hash).isNotEqualTo(PASSWORD);
        assertThat(encoder.matches(PASSWORD, hash)).isTrue();
        assertThat(jdbc.queryForObject("SELECT hire_date IS NOT NULL FROM members", Boolean.class)).isTrue();
        assertThat(count("departments")).isOne();
        assertThat(count("job_positions")).isOne();
        assertThat(output).contains("Initial admin created").doesNotContain(PASSWORD, input().email());
        assertThat(input().toString()).doesNotContain(PASSWORD, input().email(), input().name());
    }
    @Test void restartNeverResetsPasswordOrChangesAccountAndSkipsMissingInputs(CapturedOutput output) {
        run(input());
        var before = jdbc.queryForMap("SELECT * FROM members");
        run(input());
        run(new AdminBootstrapProperties(true, null, null, null));
        assertThat(jdbc.queryForMap("SELECT * FROM members")).isEqualTo(before);
        assertThat(count("members")).isOne();
        assertThat(output).contains("Admin already exists; bootstrap skipped").doesNotContain(PASSWORD);
    }
    @Test void anyExistingAdminIncludingResignedPreventsCreation() {
        ordinaryMember("other@example.test");
        jdbc.update("UPDATE member_roles SET role='ADMIN'");
        jdbc.update("UPDATE members SET status='RESIGNED'");
        run(input());
        assertThat(count("members")).isOne();
        assertThat(jdbc.queryForObject("SELECT email FROM members", String.class)).isEqualTo("other@example.test");
    }
    @Test void existingEmployeeEmailFailsWithoutPromotionOrModification(CapturedOutput output) {
        ordinaryMember(input().email());
        var before = jdbc.queryForMap("SELECT * FROM members");
        assertThatThrownBy(() -> run(input())).isInstanceOf(IllegalStateException.class).hasMessageContaining("email conflicts");
        assertThat(jdbc.queryForMap("SELECT * FROM members")).isEqualTo(before);
        assertThat(jdbc.queryForList("SELECT role FROM member_roles", String.class)).containsExactly("EMPLOYEE");
        assertThat(count("departments")).isOne();
        assertThat(output).doesNotContain(PASSWORD, input().email());
    }
    @ParameterizedTest @NullAndEmptySource
    void eachMissingInputFailsBeforeWriting(String missing) {
        for (var invalid : new AdminBootstrapProperties[] {
                new AdminBootstrapProperties(true, missing, PASSWORD, "Admin"),
                new AdminBootstrapProperties(true, input().email(), missing, "Admin"),
                new AdminBootstrapProperties(true, input().email(), PASSWORD, missing)}) {
            assertThatThrownBy(() -> run(invalid)).isInstanceOf(IllegalStateException.class).hasMessageContaining("requires valid");
        }
        assertThat(count("members")).isZero();
        assertThat(count("departments")).isZero();
    }
    @Test void invalidEmailAndWeakPasswordFollowMemberValidation() {
        assertThatThrownBy(() -> run(new AdminBootstrapProperties(true, "invalid", PASSWORD, "Admin"))).hasMessageContaining("requires valid");
        assertThatThrownBy(() -> run(new AdminBootstrapProperties(true, input().email(), "short", "Admin"))).hasMessageContaining("requires valid");
        assertThat(count("members")).isZero();
    }
    @Test void reservedIdentityIsNeverRepurposed() {
        jdbc.update("INSERT INTO departments(code,name,is_active) VALUES(?, 'Existing',TRUE)", AdminBootstrapService.RESERVED);
        assertThatThrownBy(() -> run(input())).hasMessageContaining("reserved identity");
        assertThat(count("members")).isZero();
        assertThat(count("job_positions")).isZero();
    }
    @Test void concurrentDifferentEmailsCreateExactlyOneAdmin() throws Exception {
        var start = new CountDownLatch(1);
        var bothChecked = new CyclicBarrier(2);
        doAnswer(invocation -> {
            bothChecked.await(10, TimeUnit.SECONDS);
            // Both callers observe the initial empty DB before either tries the real UNIQUE insert.
            return false;
        }).when(departments).existsByCode(AdminBootstrapService.RESERVED);
        try (var executor = Executors.newFixedThreadPool(2)) {
            var first = executor.submit(() -> { start.await(); run(input()); return true; });
            var second = executor.submit(() -> { start.await(); run(new AdminBootstrapProperties(true, "other@example.test", PASSWORD, "Other")); return true; });
            start.countDown();
            assertThat(first.get(20, TimeUnit.SECONDS)).isTrue();
            assertThat(second.get(20, TimeUnit.SECONDS)).isTrue();
        }
        assertThat(count("members")).isOne();
        assertThat(count("departments")).isOne();
        assertThat(count("job_positions")).isOne();
        assertThat(jdbc.queryForList("SELECT role FROM member_roles", String.class)).containsExactly("ADMIN");
    }
    void ordinaryMember(String email) {
        jdbc.update("INSERT INTO departments(code,name,is_active) VALUES('ordinary','Ordinary',TRUE)");
        jdbc.update("INSERT INTO job_positions(code,name,is_active) VALUES('ordinary','Ordinary',TRUE)");
        jdbc.update("INSERT INTO members(employee_number,email,password_hash,name,department_id,job_position_id,status,hire_date) VALUES('ordinary',?,'unchanged','Ordinary',1,1,'ACTIVE',CURRENT_DATE)", email);
        jdbc.update("INSERT INTO member_roles VALUES(1,'EMPLOYEE')");
    }
}
